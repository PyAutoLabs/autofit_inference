"""The ``correlated_nd`` benchmark family: the model, priors and likelihood every leaf fits.

The single definition of the second toy-likelihood family (protocol
``wiki/project/protocol_correlated_nd.md``, ``correlated_nd@1``); the numbers are
pre-registered there and generated by ``scripts/misc/simulators/correlated_nd.py``.

- **Model.** ``D`` free parameters ``x000 … x{D-1}``, each a ``UniformPrior`` on the
  dataset's box (``priors.json``), collected in an ``af.Collection`` in key order (the
  zero-padded keys make ``model.paths`` the vector order). No assertions, no label
  symmetry: ``assertion_mechanism`` is ``none`` and the evidence offset is 0.
- **Likelihood** — a normalised density in ``theta`` (so ``ln Z = ln(box mass) - ln V``
  exactly, ``models/correlated_nd_exact.py``):

  - Gaussian: ``ln L = -0.5 |diag(lambda)^-1/2 Q^T (theta - y)|^2 - 0.5 sum ln(2 pi lambda)``;
  - banana: ``ln L = -0.5 [((x1 - y1)/sigma1)^2 + sum_j ((x_j - x1^2 - y_j)/sigma2)^2]
    - 0.5 ln(2 pi sigma1^2) - 0.5 (D-1) ln(2 pi sigma2^2)``.

  Written once with ``xp`` so the numpy callback path and the JAX path evaluate the same
  expression; the exact reference checks both against the analytic form (§6).

Import this module only after the backend environment is set
(``_autofit_inference_cli.set_backend_env``).
"""

from __future__ import annotations

from pathlib import Path

import autofit as af
import numpy as np
from models import correlated_nd_exact as exact

MODEL_ID = "correlated_nd"
FAMILY = "correlated_nd"
ASSERTION_MECHANISM = "none"


def load_dataset(dataset_path: Path) -> exact.Dataset:
    return exact.load(dataset_path)


def truth_dict(ds: exact.Dataset) -> dict[str, float]:
    return {key: float(value) for key, value in zip(ds.keys, ds.truth)}


def model_description(ds: exact.Dataset) -> str:
    if ds.kind == "gaussian":
        return (
            f"correlated Gaussian, {ds.dimension} free, condition number 10^3, "
            "uniform box priors, no assertions"
        )
    return (
        f"hybrid Rosenbrock banana (n1 = 2, n2 = {ds.dimension - 1}), {ds.dimension} free, "
        "uniform box priors, no assertions"
    )


def priors_record(ds: exact.Dataset) -> dict:
    """The priors a row was fitted with (compact: the box itself is ``priors.json``)."""
    return {
        "parameters": f"{ds.keys[0]} … {ds.keys[-1]}: UniformPrior on the dataset box",
        "box": f"dataset/{ds.name}/priors.json",
        "log_volume": ds.log_volume,
        "assertions": "none",
    }


def assertion_mechanism(ds: exact.Dataset | None = None, use_jax: bool = False) -> str:
    return ASSERTION_MECHANISM


def build_model(ds: exact.Dataset):
    """The ``D``-parameter ``af.Collection`` of uniform priors on the dataset box."""
    return af.Collection(
        **{
            key: af.UniformPrior(lower_limit=float(lo), upper_limit=float(hi))
            for key, lo, hi in zip(ds.keys, ds.lower, ds.upper)
        }
    )


def parameter_keys(model) -> list[str]:
    return [".".join(path) for path in model.paths]


class AnalysisCorrelatedND(af.Analysis):
    """The family's normalised log likelihood (module docstring). Module-level so
    DynestyStatic's checkpoint can pickle it."""

    def __init__(self, dataset: exact.Dataset, use_jax: bool = False):
        super().__init__(use_jax=use_jax)
        self.kind = dataset.kind
        self.keys = tuple(dataset.keys)
        self.y = np.asarray(dataset.y, dtype=float)
        self.normalisation = exact.max_log_likelihood(dataset)
        if dataset.kind == "gaussian":
            self.projection = np.asarray(
                dataset.eigenvectors / np.sqrt(dataset.eigenvalues)[None, :], dtype=float
            )
        else:
            self.sigma1 = float(dataset.sigma1)
            self.sigma2 = float(dataset.sigma2)

    def vector_from(self, instance):
        xp = self._xp
        return xp.stack([xp.asarray(getattr(instance, key), dtype=float) for key in self.keys])

    def log_likelihood_function(self, instance):
        xp = self._xp
        theta = self.vector_from(instance)
        y = xp.asarray(self.y)
        if self.kind == "gaussian":
            u = (theta - y) @ xp.asarray(self.projection)
            chi_squared = xp.sum(u * u)
        else:
            x1 = theta[0]
            u1 = (x1 - y[0]) / self.sigma1
            uj = (theta[1:] - x1 * x1 - y[1:]) / self.sigma2
            chi_squared = u1 * u1 + xp.sum(uj * uj)
        return self.normalisation - 0.5 * chi_squared


class TrackedAnalysisCorrelatedND(AnalysisCorrelatedND):
    """``AnalysisCorrelatedND`` that hands every evaluated log likelihood to an MLTracker
    (numpy callback path only; ``tracker`` is ``None`` under JAX, protocol §8)."""

    def __init__(self, dataset: exact.Dataset, use_jax: bool = False, tracker=None):
        super().__init__(dataset=dataset, use_jax=use_jax)
        self.tracker = tracker

    def log_likelihood_function(self, instance):
        value = super().log_likelihood_function(instance)
        if self.tracker is not None:
            self.tracker.record(float(value))
        return value
