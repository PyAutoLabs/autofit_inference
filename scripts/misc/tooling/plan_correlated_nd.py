"""Plan the ``correlated_nd`` pilot on RAL: the task table and the submit script.

Generated from :mod:`searches._correlated_nd` (the pilot's expected-run manifest and its
deferrals, protocol ``wiki/project/protocol_correlated_nd.md`` §7). Nothing here is
hand-edited: change the planner, run ``--write``, commit; ``--check`` (lint) fails when a
committed file differs from what it generates.

What it writes
--------------

- ``hpc/batch_cpu/correlated_nd/pilot.tsv`` — one line per array task (header first; the
  submit reads line ``SLURM_ARRAY_TASK_ID + 2``): one run each, every planned cell × the
  10 pilot seeds on realisation 1 (930 runs).
- ``hpc/batch_cpu/submit_correlated_nd_pilot`` — the array, ``--partition=ral`` only,
  excluding the four 252-CPU nodes, no GPU resources, the private PyAutoFit/PyAutoNerves pin
  guarded before anything runs. Every run is limited to the pilot's 4 h operational cap
  plus the run overhead (``timeout -s TERM``: the runner writes a ``Terminated`` failure
  row). The cells have no measured wall: every WALL-BASIS row is ``source: unmeasured``
  with ``probe-first: yes`` — the pilot is the probe.

    python scripts/misc/tooling/plan_correlated_nd.py            # print the plan
    python scripts/misc/tooling/plan_correlated_nd.py --write    # write table + submit
    python scripts/misc/tooling/plan_correlated_nd.py --check    # lint gate
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

ROOT = next(p for p in Path(__file__).resolve().parents if (p / "ruff.toml").exists())
if str(ROOT / "scripts" / "misc") not in sys.path:
    sys.path.insert(0, str(ROOT / "scripts" / "misc"))

from searches import _correlated_nd as cnd  # noqa: E402
from searches import _wave2 as wave2  # noqa: E402

BATCH = ROOT / "hpc" / "batch_cpu"
TABLE = BATCH / "correlated_nd" / "pilot.tsv"
SUBMIT = BATCH / "submit_correlated_nd_pilot"
RAL_ROOT = "/mnt/ral/jnightin/inference/autofit_inference"

#: Seconds added to a task's ``--time`` beyond its run's limit and kill grace.
TASK_MARGIN_S = 600.0
CPUS_PER_TASK = 2
#: 8 GB (gaussian_x3 wave 2 used 6): Nautilus keeps every point at D = 100.
MEM = "8gb"
#: 100 concurrent 2-CPU tasks = 200 CPUs, under a fifth of the five 236-CPU ``ral`` nodes.
THROTTLE = 100
EXCLUDE = "euclid-ral-compute-[1-4]"
MAIL = "james.w.nightingale@durham.ac.uk"
HEADER = ("dataset", "sampler", "settings", "config", "data_seed", "limit_s", "seed")


def slurm_time(seconds: float) -> str:
    total = int(math.ceil(seconds / 60.0)) * 60
    days, rest = divmod(total, 86400)
    hours, rest = divmod(rest, 3600)
    minutes = rest // 60
    return f"{days}-{hours:02d}:{minutes:02d}:00" if days else f"{hours:02d}:{minutes:02d}:00"


def search_call(dataset: str, sampler: str) -> str:
    return (
        f'timeout -s TERM -k {int(cnd.KILL_GRACE_S)} "$LIMIT" python3 '
        f"scripts/{dataset}/searches/{sampler}/{cnd.MODEL_TYPE}.py --wave 1 "
        '--config-name "$CONFIG" --settings "$SETTINGS" --data-seed "$DATA_SEED" '
        '--seed "$SEED" --cores 1 || echo "run '
        f"{dataset}/{sampler}/$SETTINGS/data_seed$DATA_SEED/seed$SEED exited $? (its row, if "
        'any, records the failure)"'
    )


def submit(tasks: list[cnd.Task]) -> str:
    pairs = list(dict.fromkeys((t.cell.dataset, t.cell.sampler) for t in tasks))
    time_s = max(t.budget_s for t in tasks) + TASK_MARGIN_S
    summary = cnd.summary()
    lines = [
        "#!/bin/bash -l",
        "#",
        "# GENERATED by scripts/misc/tooling/plan_correlated_nd.py -- do not edit by hand.",
        "# Change the planner, run it with --write and commit; lint runs it with --check.",
        "#",
        f"# The correlated_nd pilot (protocol correlated_nd@1, section 7): {len(tasks)} array",
        f"# tasks, one run each: {summary['planned']} planned cells x {len(cnd.SEEDS)} seeds x "
        "realisation 1",
        f"# ({summary['expected_runs']} expected, {summary['expected_runs'] - len(tasks)} deferred "
        "with reasons in searches/_correlated_nd.py).",
        f"# Each run is limited to the pilot's {cnd.PILOT_CAP_S / 3600:g} h operational cap plus "
        "the run overhead; a run",
        "# that hits it writes a Terminated failure row (a censored attempt, not a timeout).",
        "# The pilot ranks nothing; it calibrates correlated_nd@2.",
        "#",
        "# CPU jobs run on --partition=ral ONLY: never gpu, ral,gpu or gpu,ral (the human's hard",
        "# rule of 2026-09-30; PyAutoMind/policy/hpc_ral.md). No GPU resources are requested.",
        "# The --exclude keeps these small tasks off the four 252-CPU nodes, the only ones a",
        "# whole-node job of another campaign fits on. The PyAuto libraries come from the",
        f"# PRIVATE pin under {RAL_ROOT}/{wave2.PIN_DIR}/, PYTHONPATH-prefixed",
        "# below; the shared /mnt/ral/jnightin/PyAuto mirror provides only the venv and is never",
        "# pulled.",
        "#",
        "# WALL-BASIS: -- one row per cell this submit runs; no correlated_nd cell has a",
        "#   measured wall yet (the pilot is the probe; every run is capped as above)",
    ]
    for dataset, sampler in pairs:
        lines += [
            f"#   cell: {dataset}/searches/{sampler}/{cnd.MODEL_TYPE}  device: ral_cpu  "
            "precision: fp64",
            "#   lanes: 1  steps: 1  source: unmeasured  probe-first: yes",
        ]
    sbatch = {
        "-J": "cnd_pilot",
        "--partition": "ral",
        "--exclude": EXCLUDE,
        "--ntasks": 1,
        "--cpus-per-task": CPUS_PER_TASK,
        "--mem": MEM,
        "--time": slurm_time(time_s),
        "--array": f"0-{len(tasks) - 1}%{min(THROTTLE, len(tasks))}",
        "-o": "output/output.%A_%a.out",
        "-e": "error/error.%A_%a.err",
        "--mail-type": "END,FAIL",
        "--mail-user": MAIL,
    }
    for key, value in sbatch.items():
        lines.append(f"#SBATCH {key}={value}" if key.startswith("--") else f"#SBATCH {key} {value}")
    text = "\n".join(lines) + "\n"
    text += f"""
export AP_ROOT={RAL_ROOT}
source $AP_ROOT/activate.sh

# The private pin: PyAutoFit {cnd.PYAUTOFIT_PIN}, PyAutoNerves
# {cnd.PYAUTONERVES_PIN} (the gaussian_x3 wave-2 pin). Prefixed, so it wins over the
# shared checkouts that activate.sh puts on PYTHONPATH; a pilot row at any other PyAutoFit
# commit is refused by searches/_correlated_nd.admit. $AF_PIN/site holds the third-party
# packages the pin needs that the shared venv lacks ({", ".join(wave2.PIN_SITE_PACKAGES)}).
export AF_PIN=$AP_ROOT/{wave2.PIN_DIR}
export PYTHONPATH="$AF_PIN/PyAutoNerves:$AF_PIN/PyAutoFit:$AF_PIN/site${{PYTHONPATH:+:$PYTHONPATH}}"

export JAX_PLATFORMS=cpu
# Every submit exports this explicitly: without it an fp64 config silently runs fp32.
export JAX_ENABLE_X64=True
# One search per process at --cores 1, as in gaussian_x3.
export NPROC=1

echo "=========================================="
date
cd $AP_ROOT
# Refuse to run anything unless both pins are at their commits and are what imports
# (explicit exits: these hold even without activate.sh's SLURM errexit guard; the runner
# also refuses a RAL correlated_nd run at any other PyAutoFit).
test "$(git -C $AF_PIN/PyAutoFit rev-parse HEAD)" = "{cnd.PYAUTOFIT_PIN}" || {{ echo "PyAutoFit pin mismatch" >&2; exit 1; }}
test "$(git -C $AF_PIN/PyAutoNerves rev-parse HEAD)" = "{cnd.PYAUTONERVES_PIN}" || {{ echo "PyAutoNerves pin mismatch" >&2; exit 1; }}
python3 -c "import autofit, autonerves, os; pin = os.environ['AF_PIN']; assert autofit.__file__.startswith(pin) and autonerves.__file__.startswith(pin), (autofit.__file__, autonerves.__file__); print('autofit', autofit.__version__, autofit.__file__); print('autonerves', autonerves.__file__)" || {{ echo "pin import check failed" >&2; exit 1; }}

TASKS=hpc/batch_cpu/correlated_nd/pilot.tsv
LINE=$(sed -n "$((SLURM_ARRAY_TASK_ID + 2))p" "$TASKS")
if [ -z "$LINE" ]; then echo "no task line $SLURM_ARRAY_TASK_ID in $TASKS" >&2; exit 1; fi
read -r DATASET SAMPLER SETTINGS CONFIG DATA_SEED LIMIT SEED <<< "$LINE"
echo "task $SLURM_ARRAY_TASK_ID: $LINE"
case "$DATASET/$SAMPLER" in
"""
    for dataset, sampler in pairs:
        text += f"    {dataset}/{sampler})\n        {search_call(dataset, sampler)}\n        ;;\n"
    text += '    *) echo "unknown cell $DATASET/$SAMPLER" >&2; exit 1 ;;\nesac\n'
    text += '\necho "Finished."\ndate\n'
    return text


def plan() -> dict[Path, str]:
    tasks = cnd.pilot_tasks()
    table = "\t".join(HEADER) + "\n" + "".join(t.line() + "\n" for t in tasks)
    return {TABLE: table, SUBMIT: submit(tasks)}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    files = plan()
    if args.check:
        stale = [p for p, c in files.items() if not p.exists() or p.read_text() != c]
        known = {*BATCH.glob("submit_correlated_nd_*"), *TABLE.parent.glob("*.tsv")}
        extra = sorted(known - set(files))
        for path in stale + extra:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale or extra:
            print("run plan_correlated_nd.py --write", file=sys.stderr)
            return 1
        print(f"correlated_nd pilot plan is current ({len(files)} files)")
        return 0
    if args.write:
        TABLE.parent.mkdir(parents=True, exist_ok=True)
        for path, content in files.items():
            path.write_text(content)
            if path.name.startswith("submit_"):
                path.chmod(0o755)
        print(f"wrote {len(files)} files")
    tasks = cnd.pilot_tasks()
    print(f"  {len(tasks)} tasks / runs; --time per task {slurm_time(tasks[0].budget_s + 600)}")
    for dataset, n in cnd.summary()["by_dataset"].items():
        print(f"    {dataset:22s} {n:4d} runs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
